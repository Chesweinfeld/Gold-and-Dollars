def _legend(lo, hi, caption):
    """A continuous bar with five priced ticks, in dollars per square km."""
    stops = ", ".join(f"{c} {i/(len(RAMP)-1)*100:.0f}%"
                      for i, c in enumerate(RAMP))
    ticks = "".join(
        f'<span>{_money(10 ** (lo + (hi - lo) * f))}</span>'
        for f in (0, 0.25, 0.5, 0.75, 1))
    return (f'<div class="bar" id="bar" '
            f'style="background:linear-gradient(90deg,{stops})">'
            f'</div><div class="ticks">{ticks}</div>'
            f'<div class="cap">{caption}</div>')


def _legend_diverge(span, base):
    """A two-sided bar: how far the ground departs from the national ratio."""
    stops = ", ".join(f"{c} {i/(len(DIVERGE)-1)*100:.0f}%"
                      for i, c in enumerate(DIVERGE))
    # Both readings on the same bar: the multiple of the national figure, and
    # the years the multiple works out to, so nobody has to do the arithmetic.
    def _yr(x):
        if x >= 1:
            return f"{x:,.0f} year" + ("" if round(x) == 1 else "s")
        d = x * 365
        return "under a day" if d < 0.5 else f"{d:,.0f} day" + ("" if round(d) == 1 else "s")
    ticks = "".join(
        f"<span>{m}<br><i>{_yr(base * f)}</i></span>" for m, f in
        ((f"1/{10**span:,.0f}&times;", 10 ** -span),
         (f"1/{10**(span/2):,.0f}&times;", 10 ** (-span / 2)),
         ("the U.S. figure", 1.0),
         (f"{10**(span/2):,.0f}&times;", 10 ** (span / 2)),
         (f"{10**span:,.0f}&times;", 10 ** span)))
    return (f'<div class="bar" style="background:linear-gradient(90deg,{stops})">'
            f'</div><div class="ticks yrs">{ticks}</div>'
            f'<div class="cap"><b>Land value &divide; a year of the output '
            f'produced on it</b>, against the national figure of '
            f'{base:.2f} years &mdash; that is, all the land in the lower 48 is '
            f'worth about {base*12:.0f} months of what is made on it.<br>'
            f'<b style="color:#35978f">Teal</b>: the ground is cheap for the '
            f'work it carries. <b style="color:#8c510a">Brown</b>: the ground '
            f'costs more than the work on it accounts for. '
            f'<i style="background:{NOVAL};width:11px;height:11px;'
            f'display:inline-block;border-radius:2px;vertical-align:-1px"></i> '
            f'grey: no workplace here, so the output is known only by '
            f'county and no ratio is drawn.</div>')


def _money(x):
    if x >= 1e9:
        return f"${x/1e9:,.0f}bn"
    if x >= 1e6:
        return f"${x/1e6:,.0f}m"
    return f"${x/1e3:,.0f}k"


