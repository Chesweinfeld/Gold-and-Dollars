                labels=[[q, round(float(x), 1), round(float(y), 1), k]
                        for (q, (x, y)), k in zip(zip(codes, lp),
                                                  _state_zoom(lp))],
                towns=[[q, round(float(x), 1), round(float(y), 1), k]
                       for (q, (x, y)), k in zip(zip(tname, tp), townk)
                       if k <= MAX_ZOOM],
